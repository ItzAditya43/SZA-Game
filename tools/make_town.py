#!/usr/bin/env python3
"""Authoring tool: writes data/town.json, the hand-laid Prototype 1 town.

The town is a 64 x 64 tile grid (2 km x 2 km, 31.25 m per tile): a state
highway east-west, a main road north-south, ward roads, a canal along the south
edge and fields beyond it. Buildings are placed by hand below; the script only
checks they fit (inside the map, off roads and canal, not overlapping) and
writes the JSON. Edit the lists and rerun:  python3 tools/make_town.py
"""
import json
import pathlib

W = H = 64
grid = [["." for _ in range(W)] for _ in range(H)]


def fill(x0, y0, x1, y1, ch):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            grid[y][x] = ch


# Fields south of the canal, then the canal, then roads (bridge over the canal).
fill(0, 59, 63, 63, ",")
fill(0, 57, 63, 58, "~")
fill(0, 31, 63, 32, "=")      # state highway
fill(31, 0, 32, 63, "=")      # main road, bridges the canal
fill(0, 10, 63, 10, "=")      # ward road north
fill(0, 46, 63, 46, "=")      # ward road south
fill(12, 0, 12, 56, "=")      # ward road west
fill(50, 0, 50, 56, "=")      # ward road east
fill(33, 33, 38, 36, ":")     # bus stand
fill(33, 27, 48, 27, ":")     # market frontage north of the highway

HOUSE_FAMILIES = ["Iyer", "Nair", "Reddy", "Pillai", "Khan", "Joseph", "Gowda", "Naidu", "Menon", "Rao",
                  "Das", "Sheikh", "Thomas", "Kumar", "Fernandes", "Shetty", "Varma", "Hegde", "Mathew",
                  "Ansari", "Chettiar", "Krishnan", "Banu", "Raju", "Moorthy", "Pandian", "George", "Ali",
                  "Subramaniam", "Lal"]
HOUSES = [(1, 1), (6, 1), (1, 5), (6, 5),                                  # NW ward
          (14, 1), (18, 1), (22, 1), (26, 1), (14, 5), (24, 5),            # north ward
          (34, 1), (38, 1), (42, 1), (46, 1), (34, 5), (38, 5),            # NE ward
          (1, 13), (6, 13), (1, 18), (6, 18),                              # west ward
          (22, 13), (26, 13), (22, 18), (26, 18),                          # behind the police station
          (2, 42), (14, 38), (18, 38), (26, 38),                           # south ward
          (14, 49), (18, 49)]                                              # by the overhead tank

# (type, name, x, y, w, h)
OTHERS = [
    ("hospital", "District Government Hospital", 53, 2, 8, 6),
    ("police_station", "Town Police Station", 15, 13, 5, 4),
    ("school", "Government Higher Secondary School", 2, 35, 7, 5),
    ("school", "St. Mary's Convent School", 52, 48, 7, 5),
    ("water_tower", "Ward 9 Overhead Tank", 44, 13, 2, 2),
    ("water_tower", "Ward 4 Overhead Tank", 26, 49, 2, 2),
    ("petrol_pump", "Highway Petrol Bunk (west)", 2, 27, 3, 3),
    ("petrol_pump", "Highway Petrol Bunk (east)", 58, 34, 3, 3),
    ("factory", "Civil Supplies Godown", 3, 49, 6, 4),
    ("factory", "Cashew Processing Unit", 54, 38, 6, 5),
    ("pharmacy", "Sri Sai Medicals", 36, 28, 2, 2),
    ("pharmacy", "New Life Pharmacy", 44, 34, 2, 2),
    ("hardware", "Ganesh Hardwares", 40, 28, 2, 2),
    ("hardware", "Royal Hardware & Paints", 22, 34, 2, 2),
    ("kirana", "Annapoorna Stores", 33, 28, 2, 2),
    ("kirana", "Murugan Provisions", 46, 28, 2, 2),
    ("kirana", "Bismillah Kirana", 40, 34, 2, 2),
    ("kirana", "Venkateshwara Stores", 47, 34, 2, 2),
    ("kirana", "Selvi Provision Store", 14, 28, 2, 2),
    ("kirana", "Corner Shop", 20, 6, 2, 2),
]

buildings = []
for i, (x, y) in enumerate(HOUSES):
    buildings.append({"id": "house_%02d" % (i + 1), "type": "house", "name": "%s house" % HOUSE_FAMILIES[i],
                      "x": x, "y": y, "w": 3, "h": 3})
counters = {}
for type_, name, x, y, w, h in OTHERS:
    counters[type_] = counters.get(type_, 0) + 1
    buildings.append({"id": "%s_%02d" % (type_, counters[type_]), "type": type_, "name": name,
                      "x": x, "y": y, "w": w, "h": h})

taken = {}
for b in buildings:
    for y in range(b["y"], b["y"] + b["h"]):
        for x in range(b["x"], b["x"] + b["w"]):
            assert 0 <= x < W and 0 <= y < H, b
            assert grid[y][x] == ".", "%s sits on '%s' at %d,%d" % (b["id"], grid[y][x], x, y)
            assert (x, y) not in taken, "%s overlaps %s" % (b["id"], taken[(x, y)])
            taken[(x, y)] = b["id"]

# Infected at the outbreak: a thin spread everywhere plus crowds at the hospital,
# the bus stand and the market. Zones are 4 x 4, 16 tiles (500 m) square, row-major.
start = [150] * 16
start[3] += 1500    # hospital (NE)
start[10] += 1300   # bus stand and market south (x 32-47, y 32-47)
start[6] += 800     # market north of the highway (x 32-47, y 16-31)
# New infected over the first days come from where people lived.
growth = [1] * 16
for b in buildings:
    zone = (b["y"] // 16) * 4 + b["x"] // 16
    growth[zone] += 3 if b["type"] == "house" else 1

town = {
    "comment": "Generated by tools/make_town.py. Legend: . open ground, = road, ~ canal, : paved plaza, , fields.",
    "width": W, "height": H, "tile_m": 2000.0 / W,
    "rows": ["".join(r) for r in grid],
    "landmarks": [
        {"name": "Bus stand", "x": 33, "y": 33},
        {"name": "Market", "x": 37, "y": 26},
        {"name": "Canal", "x": 2, "y": 56},
        {"name": "State highway", "x": 20, "y": 30},
    ],
    "zones": {"cols": 4, "rows": 4, "size_tiles": 16, "start_infected": start, "growth_weights": growth},
    "buildings": buildings,
}
out = pathlib.Path(__file__).resolve().parent.parent / "data" / "town.json"
out.write_text(json.dumps(town, indent=1) + "\n")
print("wrote %s: %d buildings, %d infected at start" % (out, len(buildings), sum(start)))
